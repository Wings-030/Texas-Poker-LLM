export function translate(language: Language, source: string, values: Record<string, string | number> = {}): string {
  const template = language === "en" ? english[source] ?? source : source;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

export function translateGameText(language: Language, source?: string): string {
  if (!source || language === "zh") return source ?? "";
  const direct = translate(language, source);
  if (direct !== source) return direct;
  if (source.includes("；")) return source.split("；").map((part) => translateGameText(language, part)).join("; ");

  const action = source.match(/^(弃牌|过牌|跟注|下注|加注|全下)(?: (\d+))?$/);
  if (action) return `${translate(language, action[1])}${action[2] ? ` ${action[2]}` : ""}`;
  const blind = source.match(/^盲注 (\d+)$/);
  if (blind) return `Blind ${blind[1]}`;
  const handStart = source.match(/^第 (\d+) 手牌开始$/);
  if (handStart) return `Hand ${handStart[1]} begins`;
  const deal = source.match(/^发放底牌，盲注 (.+)$/);
  if (deal) return `Hole cards dealt · Blinds ${deal[1]}`;
  const streetDeal = source.match(/^(翻牌圈|转牌圈|河牌圈)发牌$/);
  if (streetDeal) return `${translate(language, streetDeal[1])} dealt`;
  const uncontested = source.match(/^(.+) 无需摊牌赢得 (\d+)$/);
  if (uncontested) return `${translate(language, uncontested[1])} wins ${uncontested[2]} without showdown`;
  const champion = source.match(/^(.+) 获得冠军$/);
  if (champion) return `${translate(language, champion[1])} wins the tournament`;
  const showdown = source.match(/^摊牌：(.+)$/);
  if (showdown) return `Showdown: ${translateGameText(language, showdown[1])}`;
  const winners = source.match(/^(.+) 赢得底池$/);
  if (winners) return `${winners[1].split("、").map((name) => translate(language, name)).join(", ")} wins the pot`;
  const playerAction = source.match(/^(.+) (弃牌|过牌|跟注|下注|加注|全下)(?: (\d+))?$/);
  if (playerAction) return `${translate(language, playerAction[1])} ${translate(language, playerAction[2])}${playerAction[3] ? ` ${playerAction[3]}` : ""}`;
  const minimum = source.match(/^最低合法金额为 (\d+)$/);
  if (minimum) return `Minimum legal amount is ${minimum[1]}`;
  return source;
}

interface I18nValue {
  language: Language;
  locale: string;
  t: (source: string, values?: Record<string, string | number>) => string;
  text: (source?: string) => string;
}

const I18nContext = createContext<I18nValue>({ language: "zh", locale: "zh-CN", t: (source) => source, text: (source) => source ?? "" });

export function I18nProvider({ language, children }: { language: Language; children: ReactNode }) {
  const value = useMemo<I18nValue>(() => ({
    language,
    locale: language === "zh" ? "zh-CN" : "en-US",
    t: (source, values) => translate(language, source, values),
    text: (source) => translateGameText(language, source),
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
